/**
 * Returns the SVG string for a given single Latin character
 */
export function getDeadGlyphSvg(char) {
  const upper = (char || '').toUpperCase();
  return DEAD_ALPHABET[upper]?.svg || '';
}

/**
 * Converts a spell string into HTML of Dead Alphabet symbols
 */
export function renderSpellSymbols(spellText) {
  if (!spellText) return '';
  const clean = spellText.toUpperCase().replace(/[^A-Z]/g, '');
  return Array.from(clean).map(char => {
    const glyph = DEAD_ALPHABET[char];
    if (!glyph) return '';
    return `<span class="dead-glyph-slot" data-char="${char}">${glyph.svg}</span>`;
  }).join('');
}

/**
 * Generates the complete 26-letter grid HTML for the Decoder panel
 */
export function renderDecoderGridHTML() {
  return Object.keys(DEAD_ALPHABET).map(letter => {
    const item = DEAD_ALPHABET[letter];
    return `
      <div class="decoder-card" data-letter="${letter}">
        <span class="decoder-latin">${letter}</span>
        <div class="decoder-symbol-wrap">${item.svg}</div>
      </div>
    `;
  }).join('');
}
